import { POLICY_VERSION } from './types.ts';
import type { Context, Story } from './types.ts';
import { displayEligible, validateStory } from './qualification.ts';
import { assertNow, canonicalUrl, dateBounds, hasSpan, instant, validLocation } from './util.ts';

/** Any edit removes publication authority. The host persists history and invalidates old manifests. */
export function reviseStory(story: Story, patch: Partial<Omit<Story, 'id' | 'version' | 'status' | 'review'>>): Story {
  const next = { ...structuredClone(story), ...structuredClone(patch), id: story.id, version: story.version + 1, status: 'pending' as const };
  delete next.review;
  if (validateStory(next).length) throw new Error('Invalid revised story');
  return next;
}
export function withdrawStory(story: Story): Story {
  return { ...structuredClone(story), version: story.version + 1, status: 'withdrawn' };
}
/** Public projection: no article body, evidence quotations, review notes, or candidate data. */
export function publicCard(story: Story, context: Context, lane: 'recent' | 'archive' = 'recent') {
  if (!displayEligible(story, context, lane)) throw new Error('Story is not currently displayable');
  const p = context.sources[story.sourceId];
  return {
    id: story.id, version: story.version, clusterId: story.clusterId,
    title: story.title, sourceId: story.sourceId, url: canonicalUrl(story.url)!,
    summary: p.permissions.summary ? story.summary : null,
    eventDate: story.eventDate?.value, datePrecision: story.eventDate?.precision,
    topics: [...story.topics], archive: lane === 'archive',
    location: structuredClone(!validLocation(story.location)
      ? { kind: 'unknown', points: [] } : story.location),
  };
}
export interface PromiseEntry {
  id: string; sourceUrl: string; entities: string[]; topic: string; quantity: string;
  deadline: string; quote: string; recordedAt: string; recordedBy: string;
}
/** Private ledger storage only. No claim of fulfillment is generated by this function. */
export function recordPromise(s: Story, context: Context, actor: string): PromiseEntry {
  const p = context.sources[s.sourceId], promise = s.promise;
  if (validateStory(s).length || !p?.enabled || p.tier === 3 || !actor.trim() || !canonicalUrl(s.url)
    || (s.stage !== 'plan' && s.frame !== 'announcement_of_intent') || !promise || !s.entities.length
    || !hasSpan(s.body, promise.quote) || !hasSpan(promise.quote, promise.quantity) || !promise.quantity.trim()
    || !dateBounds(promise.deadline) || !hasSpan(promise.quote, promise.deadline.quote)) throw new Error('Unverified plan');
  return { id: s.id + ':plan:' + s.version, sourceUrl: s.url, entities: [...s.entities], topic: s.topics[0],
    quantity: promise.quantity, deadline: promise.deadline.value, quote: promise.quote, recordedAt: context.now, recordedBy: actor };
}
export function proposePromiseMatches(story: Story, ledger: PromiseEntry[], context: Context): { promiseId: string; storyId: string; requiresHumanConfirmation: true }[] {
  if (!displayEligible(story, context) || !['completed', 'milestone'].includes(story.stage)) return [];
  const entities = new Set(story.entities.map(x => x.toLowerCase()));
  return ledger.filter(p => {
    const prior = new Set(p.entities.map(x => x.toLowerCase()));
    const union = new Set([...entities, ...prior]);
    const intersection = [...entities].filter(x => prior.has(x)).length;
    return p.topic === story.topics[0] && union.size > 0 && intersection / union.size >= .5
      && story.quantities.some(q => q.value === p.quantity);
  }).map(p => ({ promiseId: p.id, storyId: story.id, requiresHumanConfirmation: true }));
}
export interface AutomationLabel {
  eventCluster: string; sourceId: string; topics: string[]; researchStage: string;
  flags: string[]; policyVersion: string; modelVersion: string;
  action: 'approve' | 'reject'; edited: boolean; at: string;
}
/** One-sided 95% exact binomial lower bound, fixed-sample independent-trial assumption. */
export function exactLowerBound(successes: number, total: number): number {
  if (!Number.isInteger(total) || total < 1 || total > 10_000 || !Number.isInteger(successes) || successes < 0 || successes > total) throw new TypeError('Invalid binomial counts');
  if (!successes) return 0;
  const logFact = [0]; for (let i = 1; i <= total; i++) logFact[i] = logFact[i - 1] + Math.log(i);
  const tail = (p: number) => {
    let sum = 0;
    for (let k = successes; k <= total; k++) sum += Math.exp(logFact[total] - logFact[k] - logFact[total - k] + k * Math.log(p) + (total - k) * Math.log1p(-p));
    return sum;
  };
  let lo = 0, hi = 1;
  for (let i = 0; i < 70; i++) { const mid = (lo + hi) / 2; if (tail(mid) < .05) lo = mid; else hi = mid; }
  return (lo + hi) / 2;
}
/** Lower endpoint of the two-sided 95% Wilson score interval (z = 1.95996). */
export function wilsonLowerBound(successes: number, total: number): number {
  if (!Number.isSafeInteger(total) || total < 1 || !Number.isSafeInteger(successes) || successes < 0 || successes > total) throw new TypeError('Invalid binomial counts');
  if (!successes) return 0;
  const z = 1.959963984540054, z2 = z * z, p = successes / total;
  return Math.max(0, (p + z2 / (2 * total) - z * Math.sqrt(p * (1 - p) / total + z2 / (4 * total * total))) / (1 + z2 / total));
}
/** Advisory only: this engine never turns on automated publication. */
export function evaluateAutomation(labels: AutomationLabel[], options: {
  now: string; sourceId: string; topic: string; modelVersion: string; minSamples?: number; target?: number;
}) {
  const now = assertNow(options.now), min = options.minSamples ?? 100, target = options.target ?? .95;
  if (!Number.isInteger(min) || min < 1 || !Number.isFinite(target) || target <= 0 || target >= 1) throw new TypeError('Invalid automation criteria');
  const sensitive = ['health_medicine', 'governance_rights'];
  if (sensitive.includes(options.topic)) return { proposal: false, samples: 0, successes: 0, lowerBound: 0, reason: 'NEVER_AUTOMATE' };
  const cohort = labels.filter(l => l.sourceId === options.sourceId && l.topics[0] === options.topic
    && l.policyVersion === POLICY_VERSION && l.modelVersion === options.modelVersion
    && instant(l.at) !== null && instant(l.at)! <= now && now - instant(l.at)! <= 90 * 86_400_000);
  if (cohort.some(l => l.flags.length || l.topics.some(t => sensitive.includes(t)) || !['none', 'approved'].includes(l.researchStage)))
    return { proposal: false, samples: cohort.length, successes: 0, lowerBound: 0, reason: 'CLASS_NOT_CLEAN' };
  // All labels for one event must agree on an unedited approval to count as one success.
  const groups = new Map<string, AutomationLabel[]>();
  for (const l of cohort) groups.set(l.eventCluster, [...groups.get(l.eventCluster) ?? [], l]);
  const samples = groups.size, successes = [...groups.values()].filter(ls => ls.every(l => l.action === 'approve' && l.edited === false)).length;
  const lowerBound = samples ? wilsonLowerBound(successes, samples) : 0;
  return { proposal: samples >= min && lowerBound >= target, samples, successes, lowerBound,
    reason: samples < min ? 'INSUFFICIENT_SAMPLES' : lowerBound < target ? 'INSUFFICIENT_PRECISION_EVIDENCE' : 'HUMAN_POLICY_APPROVAL_REQUIRED' };
}
